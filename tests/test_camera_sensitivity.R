source('src/transcriptomics/camera_helpers.R')
fails<-function(expr){ok<-FALSE;tryCatch(force(expr),error=function(e)ok<<-TRUE);stopifnot(ok)}
md<-expand.grid(condition=c('control','psilocin_day1','psilocin_day3'),block=c('A','B','C'),stringsAsFactors=FALSE);md$analysis_unit<-paste(md$block,md$condition,sep=':')
ct<-matrix(10L,nrow=2,ncol=9,dimnames=list(c('g1','g2'),md$analysis_unit));mp<-data.frame(gene_id=c('g1','g2'),symbol=c('S1','S2'))
lev<-c('control','psilocin_day1','psilocin_day3')
x<-validate_camera_inputs(ct,md[9:1,],mp,lev,9)
stopifnot(identical(rownames(x$metadata),colnames(ct)),qr(x$design)$rank==5)
bad<-md;bad$analysis_unit[2]<-bad$analysis_unit[1];fails(validate_camera_inputs(ct,bad,mp,lev))
bad<-md;bad$analysis_unit[1]<-'unmatched';fails(validate_camera_inputs(ct,bad,mp,lev))
bad<-ct;bad[1,1]<- -1;fails(validate_camera_inputs(bad,md,mp,lev))
bad<-ct;bad[1,1]<-1.5;fails(validate_camera_inputs(bad,md,mp,lev))
bad<-md;bad$condition[1]<-'psilocin_day1';fails(validate_camera_inputs(ct,bad,mp,lev))
bad<-mp;bad$symbol[2]<-'S1';fails(validate_camera_inputs(ct,md,bad,lev))
fails(camera_contrast('unknown',x$design))
beta<-setNames(c(0,0,0,2,5),colnames(x$design))
stopifnot(sum(camera_contrast('day1_vs_control',x$design)*beta)==2,sum(camera_contrast('day3_vs_control',x$design)*beta)==5,sum(camera_contrast('day3_vs_day1',x$design)*beta)==3)
cat('CAMERA identity, count, design, reference and contrast failure tests pass.\n')
