import { openWorkspaceNavigation } from './workspace-browser-helpers.mjs';
import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
const browser = await chromium.launch({ headless: true, ...(process.env.BROWSER_PATH ? { executablePath: process.env.BROWSER_PATH } : {}) });
const page = await browser.newPage({ viewport: { width: 1280, height: 900 } }), errors = [];
page.on('pageerror', error => errors.push(error.message));
try {
  await page.goto((process.env.ATLAS_URL || 'http://127.0.0.1:4173/') + '#view=mitocarta');
  await page.locator('[data-framework7]').waitFor();
  const explorer = page.locator('.mitochondrial-explorer');
  const plot = explorer.locator('.mitochondrial-paired-enrichment');
  const evidence = explorer.locator('.mito-evidence-panel');
  const tab = name => explorer.getByRole('tab', { name, exact: true });
  await page.getByRole('heading', { name: 'MitoCarta · Mitochondrial pathways', exact: true }).waitFor();
  assert.equal(await page.locator('[data-section=mitocarta] .item-title').textContent(), 'MitoCarta');
  await plot.locator('svg[data-mito-enrichment-plot=overview]').waitFor();
  assert.equal(await tab('Enrichment').getAttribute('aria-selected'), 'true');
  assert.equal(await evidence.isVisible(), true);
  await plot.getByRole('button', { name: /Complex IV · subunits, Day 1, NES/ }).click();
  await evidence.locator('.mito-pathway-detail h3').filter({ hasText: 'Complex IV · subunits' }).waitFor();
  assert.equal(await explorer.getAttribute('data-pathway'), 'CIV_subunits');
  assert.ok(await plot.locator('svg circle[fill=none]').count() > 0);
  await plot.getByRole('button', { name: 'All tested pathways', exact: true }).click();
  await plot.locator('svg[data-mito-enrichment-plot=all]').waitFor();
  assert.equal(await plot.locator('svg [role=button]').count(), 152);
  await plot.getByRole('button', { name: 'Biological overview', exact: true }).click();
  await plot.getByLabel('Inspect mitochondrial pathway', { exact: true }).selectOption('CII_subunits');
  await evidence.getByText('No leading edge: this pathway was not tested.', { exact: false }).waitFor();
  await evidence.getByRole('button', { name: 'All curated members', exact: true }).click();
  assert.equal(await evidence.locator('.mito-pathway-genes>li').count(), 4);

  await plot.getByLabel('Inspect mitochondrial pathway', { exact: true }).selectOption('Translation');
  await tab('Complexes').click();
  assert.equal(await explorer.getAttribute('data-pathway'), 'Translation');
  await tab('Enrichment').click();
  assert.equal(await plot.locator('select[aria-label="Inspect mitochondrial pathway"]').inputValue(), 'Translation');
  await tab('Complexes').click();
  await explorer.getByRole('button', { name: 'Complex V ATP synthase' }).click();
  await explorer.locator('.mitochondrial-coverage').filter({ hasText: '21 curated structural subunits' }).waitFor();
  await explorer.getByRole('button', { name: 'Assembly factors', exact: true }).click();
  await explorer.locator('.mitochondrial-coverage').filter({ hasText: '5 curated assembly factors' }).waitFor();
  assert.equal(await explorer.getAttribute('data-pathway'), 'CV_assembly_factors');
  await tab('Enrichment').click();
  assert.equal(await plot.locator('select[aria-label="Inspect mitochondrial pathway"]').inputValue(), 'CV_assembly_factors');
  await tab('Structure').click();
  assert.equal(await page.locator('.complex-i-sheet').count(), 0);
  await explorer.getByRole('button', { name: 'Explore human complex I in 3D' }).click();
  const structure = page.locator('.complex-i-sheet');
  await structure.locator('canvas').waitFor();
  await structure.getByText('45 / 45 deposited chains map uniquely', { exact: false }).waitFor();
  await structure.getByLabel('Select complex I subunit').selectOption({ index: 5 });
  await structure.getByRole('button', { name: 'Day 3', exact: true }).click();
  await structure.locator('.complex-i-selected-summary').filter({ hasText: 'Day 3:' }).waitFor();
  await structure.getByRole('button', { name: 'Done', exact: true }).click();
  await structure.waitFor({ state: 'detached' });

  await explorer.locator('.mito-resources .gene-annotation-toggle').click();
  await explorer.getByRole('button', { name: 'Download all 298 rows' }).waitFor();
  assert.equal(await explorer.locator('.mitochondrial-enrichment tbody tr').count(), 149);
  await explorer.locator('.mito-resources .gene-annotation-toggle').click();
  await page.setViewportSize({ width: 390, height: 844 });
  await tab('Enrichment').click();
  await plot.locator('svg[data-mito-enrichment-plot=overview]').waitFor();
  await plot.getByLabel('Inspect mitochondrial pathway', { exact: true }).selectOption('CIII_subunits');
  const sheet = page.locator('.mito-evidence-sheet.modal-in');
  await sheet.waitFor();
  await sheet.locator('.mito-pathway-detail h3').filter({ hasText: 'Complex III · subunits' }).waitFor();
  await sheet.getByRole('button', { name: 'Expand pathway evidence', exact: true }).click();
  await sheet.getByRole('button', { name: 'Collapse pathway evidence', exact: true }).waitFor();
  await sheet.getByRole('button', { name: 'Day 3 genes', exact: true }).click();
  assert.equal(await explorer.getAttribute('data-day'), '3');
  assert.equal(await sheet.evaluate(node => node.scrollWidth > node.clientWidth + 2), false);
  await page.setViewportSize({ width: 1280, height: 900 });
  await page.locator('.mito-evidence-sheet').waitFor({ state: 'detached' });
  await evidence.locator('.mito-pathway-detail h3').filter({ hasText: 'Complex III · subunits' }).waitFor();
  assert.equal(await explorer.getAttribute('data-day'), '3');
  await tab('Complexes').click();
  await explorer.locator('.mitochondrial-coverage').filter({ hasText: 'Complex III · 10 curated structural subunits' }).waitFor();
  await page.setViewportSize({ width: 390, height: 844 });
  await explorer.locator('.mito-evidence-launch').click();
  await page.locator('.mito-evidence-sheet.modal-in').waitFor();
  await page.locator('.mito-evidence-sheet .mito-gene-send').first().click();
  await page.waitForFunction(() => location.hash.includes('view=custom-r'));
  await page.locator('.mito-evidence-sheet').waitFor({ state: 'detached' });
  await page.locator('.studio-selection-card:not([hidden])').waitFor();
  await page.setViewportSize({ width: 1280, height: 900 });
  await openWorkspaceNavigation(page);
  assert.equal(await page.locator('.analysis-search').evaluate(node => node.inert), true);
  await page.getByRole('button', { name: 'Find analyses', exact: true }).click();
  assert.equal(await page.locator('.analysis-search').evaluate(node => node.inert), false);
  await page.getByRole('button', { name: 'Close analysis search', exact: true }).click();
  assert.equal(await page.locator('.analysis-search').evaluate(node => node.inert), true);
  await page.getByRole('button', { name: 'New analysis', exact: true }).click();
  assert.deepEqual(errors, []);
  console.log('PASS: native tabs, shared pathway/day selection, desktop evidence, expandable mobile sheet, responsive reparenting, complete results, lazy assembly and Send to R. No screenshots.');
} finally {
  await browser.close();
}
